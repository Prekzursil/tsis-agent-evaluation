#!/usr/bin/env python3
"""Second-chance scan of the watchdog-skipped privacy files (round 2 fix, v2).

The whole-corpus scanner skipped 500-file chunks whenever one pathological file
wedged the pool (2,271 paths). Most of those files are small and were only
collateral damage. This driver re-scans them with a single parallel pool
(6 workers, files sorted mid-size-first so giants run as workers free up) and
a per-file timeout; results are appended incrementally to
scan_skipped_results.jsonl so a kill never loses work (idempotent restart:
already-scanned paths are skipped). Files that time out remain honestly
recorded as skipped.

Then it rewrites privacy_partial.jsonl (per-path, stats preferred over
skipped) and regenerates privacy_scan_full2.json exactly from it.
Counts/ratios only; paths persisted username-redacted (<USER>).

Usage: python scan_skipped.py [--workers 6] [--per-file-timeout 1800]
"""
import argparse
import collections
import json
import os
import sys
import time
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

HERE = Path(__file__).resolve().parent
CORPUS = HERE.parent.parent / "corpus"
sys.path.insert(0, str(HERE))
from privacy_scan_corpus import scan_one, redact  # noqa: E402  (<USER> redaction)

RESULTS_PATH = HERE / "scan_skipped_results.jsonl"


def regen_aggregate(entries):
    """entries: dict redacted_path -> entry (stats or skipped). Rebuilds the
    privacy_scan_full2.json payload exactly from the ledger."""
    def new_acc():
        return {"files": 0, "unreadable": 0, "lines": 0, "json_lines": 0,
                "non_json_lines": 0, "message_objects": 0, "bytes": 0, "cats": {}}

    def merge(a, b):
        for k in ("files", "unreadable", "lines", "json_lines", "non_json_lines",
                  "message_objects", "bytes"):
            a[k] += b.get(k, 0)
        for c, v in b["cats"].items():
            a["cats"][c] = a["cats"].get(c, 0) + v

    glob = new_acc()
    by_drive = collections.defaultdict(new_acc)
    by_origin = collections.defaultdict(new_acc)
    by_runtime = collections.defaultdict(new_acc)
    skipped = 0
    for e in entries.values():
        if e.get("skipped") or "stats" not in e:
            skipped += 1
            continue
        merge(glob, e["stats"])
        merge(by_drive[e.get("drive", "?")], e["stats"])
        merge(by_origin[e.get("origin", "?")], e["stats"])
        merge(by_runtime[e.get("runtime", "?")], e["stats"])
    total_lines = max(glob["lines"], 1)

    def group_out(v):
        return {"files": v["files"], "lines": v["lines"],
                "message_objects": v["message_objects"],
                "cats": {c: {"lines": x, "line_ratio": round(x / max(v["lines"], 1), 5)}
                         for c, x in sorted(v["cats"].items(), key=lambda kv: -kv[1])}}

    return {
        "source": "tss/tsis-deepdive/corpus/manifest.jsonl (status=ok records; both "
                  "drives, all runtimes, live+backup+orphan-backup)",
        "files_scanned": glob["files"], "unreadable_files": glob["unreadable"],
        "bytes_scanned": glob["bytes"], "total_lines": glob["lines"],
        "message_objects": glob["message_objects"],
        "json_line_rate": round(glob["json_lines"] / total_lines, 4),
        "message_object_ratio": round(glob["message_objects"] / total_lines, 4),
        "pii_ish": {c: {"lines": v, "line_ratio": round(v / total_lines, 5)}
                    for c, v in sorted(glob["cats"].items(), key=lambda kv: -kv[1])},
        "by_drive": {d: group_out(v) for d, v in by_drive.items()},
        "by_origin": {o: group_out(v) for o, v in by_origin.items()},
        "by_runtime_top": {r: group_out(v) for r, v in
                           sorted(by_runtime.items(), key=lambda kv: -kv[1]["lines"])[:25]},
        "note": "aggregate counts/ratios only; no content or matched text is emitted. "
                "Line-mode files (jsonl/zst/gz/plain): every line; each "
                "line-equivalent's first 64KB pattern-scanned; newline-less payload "
                "runs flushed as 1MB capped segments; JSON detection capped at 1MB. "
                "Binary containers (sqlite + 'other', incl. the 41GB tar): 64KB "
                "blocks, each block counted as a line-equivalent; no JSON detection. "
                "Regenerated by scan_skipped.py from the deduplicated, "
                "username-redacted privacy_partial.jsonl ledger, which is the single "
                "source of truth for this aggregate.",
        "partial_entries": len(entries),
        "skipped_by_watchdog": skipped,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=6)
    ap.add_argument("--per-file-timeout", type=float, default=1800.0)
    args = ap.parse_args()

    man = {}
    with (CORPUS / "manifest.jsonl").open(encoding="utf-8") as fh:
        for line in fh:
            try:
                r = json.loads(line)
            except Exception:
                continue
            if r.get("status") == "ok":
                man[redact(r["path"])] = (r.get("storage_type") or "other",
                                          r.get("size") or 0,
                                          r.get("drive") or "?",
                                          r.get("origin") or "?",
                                          r.get("runtime") or "?")

    entries = {}
    with (HERE / "privacy_partial.jsonl").open(encoding="utf-8") as fh:
        for line in fh:
            try:
                e = json.loads(line)
            except Exception:
                continue
            p = e["path"]
            if p in entries and "stats" in entries[p] and "stats" not in e:
                continue  # keep stats over skipped
            entries[p] = e

    # incremental results from a previous (possibly killed) run
    already = set()
    if RESULTS_PATH.exists():
        with RESULTS_PATH.open(encoding="utf-8") as fh:
            for line in fh:
                try:
                    already.add(json.loads(line)["path"])
                except Exception:
                    pass

    todo_all = [p for p, e in entries.items()
                if (e.get("skipped") or "stats" not in e) and p in man]
    todo = [p for p in todo_all if p not in already]
    # mid-size first: workers chew through them while the giants (submitted last,
    # each pinned to a worker for up to per-file-timeout) finish in parallel
    todo.sort(key=lambda p: (man[p][1] or 0))
    print(f"[scan_skipped] skipped ledger entries: {len(todo_all)}; already scanned "
          f"by a prior pass: {len(already)}; scanning now: {len(todo)}", flush=True)

    home = Path.home().name
    results = {}
    timeouts = []
    t0 = time.time()
    ex = ProcessPoolExecutor(max_workers=args.workers)
    outf = RESULTS_PATH.open("a", encoding="utf-8")
    futs = {}
    try:
        for p in todo:
            real = p.replace("<USER>", home)
            futs[ex.submit(scan_one, (real, man[p][0]))] = p
        done = 0
        for fut in as_completed(futs):
            p = futs[fut]
            try:
                st = fut.result(timeout=args.per_file_timeout)
            except Exception:
                timeouts.append(p)
                continue
            _, _, drive, origin, runtime = man[p]
            rec = {"path": p, "drive": drive, "origin": origin,
                   "runtime": runtime, "stats": st}
            results[p] = rec
            outf.write(json.dumps(rec, separators=(",", ":")) + "\n")
            done += 1
            if done % 100 == 0:
                print(f"[scan_skipped] {done}/{len(todo)} scanned, "
                      f"{len(timeouts)} timed out ({time.time()-t0:.0f}s)", flush=True)
    finally:
        outf.flush()
        outf.close()
        ex.shutdown(wait=False, cancel_futures=True)
    # futures still running at pool shutdown: unknown outcome; treat as not-scanned
    # (they are neither in results nor timeouts; they stay skipped this run)
    unknown = [p for f, p in futs.items() if not f.done()]
    print(f"[scan_skipped] scan phase done in {time.time()-t0:.0f}s: "
          f"{len(results)} scanned, {len(timeouts)} per-file timeouts, "
          f"{len(unknown)} abandoned at shutdown", flush=True)

    # ---- rewrite ledger: stats-preferred per path
    n_upgraded = 0
    for p, rec in results.items():
        entries[p] = rec
        n_upgraded += 1
    with (HERE / "privacy_partial.jsonl").open("w", encoding="utf-8") as fh:
        for p, e in entries.items():
            fh.write(json.dumps(e, separators=(",", ":")) + "\n")

    out = regen_aggregate(entries)
    (HERE / "privacy_scan_full2.json").write_text(json.dumps(out, indent=2),
                                                  encoding="utf-8")
    print(f"[scan_skipped] DONE: upgraded {n_upgraded} this run; still skipped "
          f"{out['skipped_by_watchdog']} of {len(entries)}; aggregate: "
          f"files={out['files_scanned']:,} lines={out['total_lines']:,} "
          f"msgs={out['message_objects']:,}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
